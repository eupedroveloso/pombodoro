/* Cada pose vira um canvas uma vez só — depois é drawImage, como no
   spriteCanvas de sprites.js. comCoco entra na chave do cache. */
const cache = new Map()

export function pessoaCanvas(iPessoa, pose, comCoco = false) {
  const chave = `${iPessoa}|${pose}|${comCoco ? 1 : 0}`
  if (cache.has(chave)) return cache.get(chave)

  const pessoa = PESSOAS[iPessoa % PESSOAS.length]
  const mapa = pessoa.mapas[pose] || pessoa.mapas.parado1

  const alt = mapa.length
  const larg = mapa[0].length
  const cv = document.createElement('canvas')
  cv.width = larg
  cv.height = alt
  const ctx = cv.getContext('2d')

  for (let y = 0; y < alt; y++) {
    for (let x = 0; x < larg; x++) {
      const c = PALETA_PESSOAS[mapa[y][x]]
      if (!c) continue
      ctx.fillStyle = c
      ctx.fillRect(x, y, 1, 1)
    }
  }

  if (comCoco) {
    const { mapa: mc, ancoraPorPose } = pessoa.overlayCoco
    const [dx, dy] = ancoraPorPose[pose] || ancoraPorPose.parado1
    for (let y = 0; y < mc.length; y++)
      for (let x = 0; x < mc[y].length; x++) {
        const c = PALETA_PESSOAS[mc[y][x]]
        if (!c) continue
        const px2 = x + dx
        const py2 = y + dy
        if (px2 >= 0 && py2 >= 0 && px2 < larg && py2 < alt) {
          ctx.fillStyle = c
          ctx.fillRect(px2, py2, 1, 1)
        }
      }
  }

  cache.set(chave, cv)
  return cv
}
